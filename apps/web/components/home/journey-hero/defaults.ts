export function mergeConfig(partial?: DeepPartial<JourneyConfig>): JourneyConfig {
  if (!partial) return defaultConfig;
  const d = defaultConfig;
  return {
    ...d,
    ...(partial as object),
    copy: {
      ...d.copy,
      ...partial.copy,
      lines: (partial.copy?.lines as JourneyConfig["copy"]["lines"]) ?? d.copy.lines,
      trustBadges: (partial.copy?.trustBadges as JourneyConfig["copy"]["trustBadges"]) ?? d.copy.trustBadges,
    } as JourneyConfig["copy"],
    origin: { ...d.origin, ...partial.origin } as JourneyConfig["origin"],
    destination: { ...d.destination, ...partial.destination } as JourneyConfig["destination"],
    steps: (partial.steps as JourneyConfig["steps"]) ?? d.steps,
    brand: { ...d.brand, ...partial.brand },
    cities: (partial.cities as JourneyConfig["cities"]) ?? d.cities,
    theme: { ...d.theme, ...partial.theme } as JourneyConfig["theme"],
    motion: { ...d.motion, ...partial.motion },
    focus: { ...d.focus, ...partial.focus },
  };
}

